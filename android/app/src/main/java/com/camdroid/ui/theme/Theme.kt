    surfaceContainerHigh = md_theme_dark_surfaceContainerHigh,
    surfaceContainerHighest = md_theme_dark_surfaceContainerHighest,
)

/**
 * CamDroid theme — Material You (dynamic colors) on Android 12+,
 * falls back to the refined static dark palette on older devices.
 *
 * Always dark theme since this is a camera app.
 */
@Composable
fun CamDroidTheme(content: @Composable () -> Unit) {
    val colorScheme = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.S) {
        dynamicDarkColorScheme(LocalContext.current)
    } else {
        StaticDarkColorScheme
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = CamDroidTypography,
        content = content
    )
}
